#!/usr/bin/env python3
"""Generate ``patch-mode/continue_hook.py`` from the shared engine.

Why a generator
---------------
Patch mode drops a single file into the Hermes core tree
(``agent/continue_hook.py``), so that file has to be self-contained — it
cannot import ``detector.py`` from this repository, which will not be next to
it on the user's machine.

The first version of that file was a *second implementation* of the detector:
its own patterns, its own defaults, its own key names, and a hardcoded
``~/moneymaker/state/…`` log path. It drifted from the shared engine within
days, and on a machine without that directory it wrote into the wrong place.

So the file is generated instead of maintained: the detector and the decision
service are concatenated into one module, with the shared engine's behaviour
and paths. One source of truth, still self-contained.

Run it after changing the engine:

    python3 scripts/build-patch-mode.py

``tests/test_patch_mode.py`` fails when the generated file is out of date.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DETECTOR = REPO / "detector.py"
HOOKCTL = REPO / "hookctl.py"
TARGET = REPO / "patch-mode" / "continue_hook.py"

HEADER = '''"""continue-hook — patch mode (GENERATED FILE, do not edit).

Generated by ``scripts/build-patch-mode.py`` from ``detector.py`` and
``hookctl.py``. This file is dropped into the Hermes core tree as
``agent/continue_hook.py``, so it has to be self-contained — but it must never
be a *second* implementation of the rules: everything below is the shared
engine, concatenated.

Regenerate with:

    python3 scripts/build-patch-mode.py

Entry point used by the core stop gate:

    continue_hook_nudge(agent, final_response) -> str | None
"""
from __future__ import annotations

import json
import os
import re
import time
from pathlib import Path
from typing import Any

'''

FOOTER = '''

# ── the Hermes core seam ────────────────────────────────────────────────────
def continue_hook_enabled() -> bool:
    """Is the core gate switched on?

    ``agent.continue_hook_enabled`` is the documented switch, and it defaults
    to **off** — installing the patch must not start nudging turns behind the
    user's back. The earlier version fell through to the shared config's
    ``enabled`` (default true), so the switch did nothing and the gate ran as
    soon as it was installed.
    """
    switch = None
    try:
        from hermes_cli.config import load_config

        switch = (load_config().get("agent") or {}).get("continue_hook_enabled")
    except Exception:
        switch = None
    if switch is None:
        # Nothing configured (a fresh install, a test, a bare import): the gate
        # stays off rather than guessing. HERMES_CONTINUE_HOOK=1 is the
        # explicit opt-in; HERMES_CONTINUE_HOOK=0 is the kill switch below.
        return os.environ.get("HERMES_CONTINUE_HOOK") == "1"
    return bool(switch)


def continue_hook_nudge(agent, final_response) -> str | None:
    """The stop-gate entry point. Called by ``turn_stop_gates.apply_stop_gates``.

    Returns the nudge text to feed back into the turn, or ``None`` to let the
    turn end. Every failure is silent: a broken gate must not break the loop.
    """
    try:
        if os.environ.get("HERMES_CONTINUE_HOOK") == "0":
            return None
        if not continue_hook_enabled():
            return None
        session_id = str(getattr(agent, "session_id", "") or "hermes")
        platform = str(getattr(agent, "platform", "") or "")
        attempt = int(getattr(agent, "_continue_hook_nudges", 0) or 0)
        decision = decide(str(final_response or ""), session_id=session_id,
                          host="hermes-patch", platform=platform)
        if not decision.should_nudge:
            return None
        agent._continue_hook_nudges = attempt + 1
        return build_nudge(decision.attempt)
    except Exception:
        return None
'''

PLAIN_DECISION = '''class Decision:
    """The verdict for one evaluation.

    A plain class rather than a dataclass: the core imports this file with
    ``importlib.util.spec_from_file_location`` and does not always register
    it in ``sys.modules`` — and ``@dataclass`` looks the module up there,
    which would make the import fail.
    """

    __slots__ = ("attempt", "reason", "should_nudge")

    def __init__(self, should_nudge: bool, reason: str, attempt: int = 0):
        self.should_nudge = should_nudge
        self.reason = reason
        self.attempt = attempt

    def __repr__(self) -> str:
        return (f"Decision(should_nudge={self.should_nudge!r}, "
                f"reason={self.reason!r}, attempt={self.attempt!r})")

    def to_json(self) -> dict[str, Any]:
        return {
            "should_nudge": self.should_nudge,
            "reason": self.reason,
            "attempt": self.attempt,
        }
'''


def _strip_module_preamble(source: str) -> str:
    """Drop the ``from __future__`` line and the module docstring."""
    text = source.replace("from __future__ import annotations\n", "", 1)
    match = re.match(r'\s*"""(?:.|\n)*?"""\n', text)
    if match:
        text = text[match.end() :]
    return text


def _strip_cli_section(source: str) -> str:
    """Remove the CLI block — the core module has no ``__main__``.

    The CLI is the last thing in both modules, so everything from
    ``def _cli(`` to the end goes.
    """
    marker = "def _cli("
    index = source.find(marker)
    if index < 0:
        return source
    return source[:index]


_IMPORT_LINE = re.compile(r"^(?:from\s+\S+\s+import\s+.+|import\s+.+)$")


def _strip_imports(source: str) -> str:
    """Remove the module's own import block.

    The generated file gets one combined, sorted import block instead — two
    concatenated blocks would not be sorted, and ruff (which runs over this
    repository) would say so.
    """
    lines = source.splitlines()
    out: list[str] = []
    in_block = False
    for line in lines:
        stripped = line.strip()
        # Only a *top-level* import (no indentation) belongs to the module
        # block. An import inside a function — ``import fcntl`` inside the
        # state lock — must stay.
        top_level = line == stripped
        if not in_block and top_level and _IMPORT_LINE.match(stripped):
            in_block = True
            continue
        if in_block:
            if top_level and stripped and not _IMPORT_LINE.match(stripped):
                in_block = False
                out.append(line)
            elif not top_level:
                # an indented line inside the import block (a continuation)
                continue
            continue
        out.append(line)
    return "\n".join(out)


def _replace_decision_class(source: str) -> str:
    """Swap the dataclass for a plain class (see PLAIN_DECISION)."""
    pattern = re.compile(
        r"@dataclass\(frozen=True\)\nclass Decision:\n(?:.*?\n)*?\n\ndef ",
        re.S,
    )
    if not pattern.search(source):
        raise SystemExit(
            "build-patch-mode: the Decision class changed — "
            "update _replace_decision_class in this script"
        )
    return pattern.sub("__DECISION__\n\ndef ", source, count=1).replace(
        "__DECISION__", PLAIN_DECISION.rstrip("\n")
    )


def build() -> str:
    detector = _strip_module_preamble(DETECTOR.read_text(encoding="utf-8"))
    hookctl = _strip_module_preamble(HOOKCTL.read_text(encoding="utf-8"))
    detector = _strip_cli_section(detector)
    hookctl = _strip_cli_section(hookctl)
    hookctl = _replace_decision_class(hookctl)
    # The concatenated module cannot use the relative-import fallback.
    for block in (
        "try:  # package load (installed as a Python distribution)\n"
        "    from .detector import ConfigStore, detect  # type: ignore[attr-defined]\n"
        "except ImportError:  # flat execution (repo layout, tests)\n"
        "    from detector import ConfigStore, detect  # type: ignore[no-redef]\n",
        "try:  # package load (installed as a Python distribution)\n"
        "    from .detector import ConfigStore, detect  # type: ignore[attr-defined]\n"
        "except ImportError:  # flat execution (repo layout, npm package, shell hooks)\n"
        "    from detector import ConfigStore, detect  # type: ignore[no-redef]\n",
    ):
        detector = detector.replace(block, "")
        hookctl = hookctl.replace(block, "")
    detector = _strip_imports(detector)
    hookctl = _strip_imports(hookctl)
    # The concatenated module cannot use the relative-import fallback.
    for block in (
        "try:  # package load (installed as a Python distribution)\n"
        "    from .detector import ConfigStore, detect  # type: ignore[attr-defined]\n"
        "except ImportError:  # flat execution (repo layout, tests)\n"
        "    from detector import ConfigStore, detect  # type: ignore[no-redef]\n",
        "try:  # package load (installed as a Python distribution)\n"
        "    from .detector import ConfigStore, detect  # type: ignore[attr-defined]\n"
        "except ImportError:  # flat execution (repo layout, npm package, shell hooks)\n"
        "    from detector import ConfigStore, detect  # type: ignore[no-redef]\n",
    ):
        detector = detector.replace(block, "")
        hookctl = hookctl.replace(block, "")
    parts = [HEADER, detector.rstrip(), "\n", hookctl.rstrip(), "\n", FOOTER]
    generated = "".join(parts)
    # Two blank lines at most: the concatenated sources leave stray gaps where
    # the import blocks were, and ruff's import sorter objects to them.
    generated = re.sub(r"\n{4,}", "\n\n\n", generated)
    generated = re.sub(r"\n{3,}(?=[^\n])", "\n\n", generated)
    return generated


def main() -> int:
    generated = build()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != generated:
            print(
                "✗ patch-mode/continue_hook.py is out of date — "
                "run: python3 scripts/build-patch-mode.py"
            )
            return 1
        print("✓ patch-mode/continue_hook.py is up to date")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(generated, encoding="utf-8")
    print(f"✓ wrote {TARGET.relative_to(REPO)} ({len(generated.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
